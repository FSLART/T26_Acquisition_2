// AQT2 (0x720, front wheel rpm, raw = rpm). Sent every 10 ms from the TIM7 interrupt, so nothing in
// the main loop can delay it. thermal_can.c leaves one TX mailbox free and queues under a critical section.
static void send_wheel_speed_frame(void) {
    static uint32_t last_queued_ms;
    CAN_TxHeaderTypeDef header = { .StdId = DATA_T26_AQT2_FRAME_ID, .IDE = CAN_ID_STD,
                                   .RTR = CAN_RTR_DATA, .DLC = DATA_T26_AQT2_LENGTH };
    uint8_t payload[8];
    uint32_t mailbox;

    wheel_speed_update();
    struct data_t26_aqt2_t message = {
        .front_left_wheel_rpm  = (uint16_t)(wheel_speed[0].rpm + 0.5f),
        .front_right_wheel_rpm = (uint16_t)(wheel_speed[1].rpm + 0.5f),
    };
    data_t26_aqt2_pack(payload, &message, sizeof(payload));

    if (HAL_CAN_AddTxMessage(&hcan1, &header, payload, &mailbox) != HAL_OK) {
        aqt2.can.tx_queue_fail++;
        return;
    }
    if (aqt2.can.tx_queued && time_ms - last_queued_ms > aqt2.can.wheel_frame_max_gap_ms) {
        aqt2.can.wheel_frame_max_gap_ms = time_ms - last_queued_ms;
    }
    last_queued_ms = time_ms;
    aqt2.can.tx_queued++;
    memcpy((void *)aqt2.can.last_tx, payload, DATA_T26_AQT2_LENGTH);
}

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef* htim){
    if (htim->Instance == TIM7) {
        time_ms++;
        if (time_ms % 10 == 0) {
            send_wheel_speed_frame();
        }
    } else if (htim->Instance == TIM3) {
        wheel_speed_timer_overflow();
    }
}

// Rising edges on PB0 (TIM3_CH3) and PB1 (TIM3_CH4)
void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim) {
    if (htim->Instance != TIM3) {
        return;
    }
    if (htim->Channel == HAL_TIM_ACTIVE_CHANNEL_3) {
        wheel_speed_capture(0, HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_3));
    }
    if (htim->Channel == HAL_TIM_ACTIVE_CHANNEL_4) {
        wheel_speed_capture(1, HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_4));
    }
}

