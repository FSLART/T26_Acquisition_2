void HAL_CAN_ErrorCallback(CAN_HandleTypeDef *hcan) {
    aqt2.can.err_count++;
    aqt2.can.last_error = hcan->ErrorCode;
    aqt2.can.error_flags |= hcan->ErrorCode;
    HAL_CAN_ResetError(hcan);
}
