        uint8_t  error_passive;
        uint8_t  error_warning;
        uint8_t  free_mailboxes;    // 0..3
        uint8_t  state;             // HAL_CAN_StateTypeDef (2 = LISTENING = running)
        uint8_t  last_tx[8];        // payload of the last queued 0x720 frame
